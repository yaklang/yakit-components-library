import { readIconInput } from './icon-source-documents.mjs';
import { readIconSources } from './icon-source-data.mjs';
const colorfulSource = readIconSources().colorful;
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

import {
  colorfulComponentNodeId,
  colorfulLocalFile,
  validateColorfulInventory,
} from './colorful-icon-contracts.mjs';

const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC_EXPOSURES = new Set(['canonical', 'semantic-alias']);
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

function fail(code, message) {
  throw new Error(`${code}: ${message}`);
}

const typescriptString = (value) => {
  if (value === null) return 'null';
  return `'${String(value)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')}'`;
};

function publicRows(inventory) {
  const canonicalRows = new Map(
    inventory.rows
      .filter((row) => row.rowDisposition === 'canonical-new')
      .map((row) => [colorfulComponentNodeId(row), row]),
  );
  return inventory.rows
    .filter((row) => PUBLIC_EXPOSURES.has(row.publicExposure))
    .map((row) => {
      const canonical =
        row.publicExposure === 'canonical' ? row : canonicalRows.get(row.canonicalComponentNodeId);
      if (!canonical) fail('CANONICAL_TARGET_UNKNOWN', row.canonicalComponentNodeId);
      if (!IDENTIFIER.test(row.exportName)) fail('PUBLIC_EXPORT_INVALID', row.exportName);
      return {
        ...row,
        canonicalExportName: canonical.exportName,
        canonicalLocalFile: colorfulLocalFile(canonical),
        paintMode: row.paintMode ?? canonical.paintMode,
      };
    });
}

export function renderColorfulBarrel(inventory) {
  const rows = publicRows(inventory);
  const canonicalRows = rows
    .filter((row) => row.publicExposure === 'canonical')
    .sort((left, right) => left.canonicalLocalFile.localeCompare(right.canonicalLocalFile));
  const imports = canonicalRows.map((row) => {
    const file = path.posix.basename(row.canonicalLocalFile);
    return `import ${row.exportName}Svg from ${typescriptString(`./${file}?react`)};`;
  });
  const exports = rows.map((row) => {
    const svgOwner = `${row.canonicalExportName}Svg`;
    return `export const ${row.exportName} = createIcon(
  ${svgOwner},
  ${typescriptString(row.exportName)},
);`;
  });
  return [
    '// Generated by scripts/colorful-entry-generator.mjs. Do not edit manually.',
    '',
    "import { createIcon } from '../createIcon.js';",
    '',
    "export type { IconComponent, IconProps, IconRef, IconSvgProps } from '../types.js';",
    '',
    ...imports,
    '',
    ...exports,
    '',
  ].join('\n');
}

export function renderColorfulCatalog(inventory) {
  const rows = publicRows(inventory);
  const entries = rows.map((row) => ({
    category: row.category,
    exportName: row.exportName,
    family: 'colorful',
    figmaName: row.figmaName ?? null,
    paintMode: row.paintMode,
    sourceNodeId: colorfulComponentNodeId(row),
    sourceStatus: row.sourceStatus ?? 'current',
  }));
  const body = entries
    .map(
      (entry) => `  {
    category: ${typescriptString(entry.category)},
    exportName: ${typescriptString(entry.exportName)},
    family: 'colorful',
    figmaName: ${typescriptString(entry.figmaName)},
    paintMode: ${typescriptString(entry.paintMode)},
    sourceNodeId: ${typescriptString(entry.sourceNodeId)},
    sourceStatus: ${typescriptString(entry.sourceStatus)},
  },`,
    )
    .join('\n');
  return [
    '// Generated by scripts/colorful-entry-generator.mjs. Do not edit manually.',
    '',
    "import type { ColorfulIconCategory, ColorfulIconPaintMode } from './types.js';",
    '',
    'export interface ColorfulIconNameCatalogEntry {',
    '  category: ColorfulIconCategory;',
    '  exportName: string;',
    "  family: 'colorful';",
    '  figmaName: string | null;',
    '  paintMode: ColorfulIconPaintMode;',
    '  sourceNodeId: string;',
    "  sourceStatus: 'current' | 'supplement' | 'unnamed-in-figma' | 'legacy-non-current-figma';",
    '}',
    '',
    'export const colorfulIconNameCatalog = [',
    body,
    '] as const satisfies readonly ColorfulIconNameCatalogEntry[];',
    '',
  ].join('\n');
}

function option(args, name, fallback) {
  const index = args.indexOf(name);
  return index < 0 ? fallback : args[index + 1];
}

export async function runColorfulEntryGenerator(args = process.argv.slice(2)) {
  if (args.includes('--write'))
    fail('COLORFUL_ENTRY_WRITE_RETIRED', 'Use pnpm icons:update --family colorful');
  const manifestPath = path.resolve(
    PACKAGE_ROOT,
    option(args, '--manifest', 'config/icon-sources/colorful.json#manifest'),
  );
  const inventory = JSON.parse(await readIconInput(manifestPath, 'utf8'));
  validateColorfulInventory(inventory, {
    expectedGroupCount: Number(
      option(args, '--expected-groups', String(colorfulSource.groups.length)),
    ),
    expectedRowCount: Number(
      option(args, '--expected-rows', String(colorfulSource.records.length)),
    ),
    requireFrozenClassification: true,
    requireProvenance: true,
  });
  const rawOutputs = [
    {
      content: renderColorfulBarrel(inventory),
      path: path.resolve(PACKAGE_ROOT, 'src/icons/colorful/index.tsx'),
    },
    {
      content: renderColorfulCatalog(inventory),
      path: path.resolve(PACKAGE_ROOT, 'src/icons/colorful/catalog.ts'),
    },
  ];
  const prettierConfig = (await resolveConfig(rawOutputs[0].path)) ?? {};
  const outputs = await Promise.all(
    rawOutputs.map(async (output) => ({
      ...output,
      content: await format(output.content, {
        ...prettierConfig,
        filepath: output.path,
      }),
    })),
  );
  for (const output of outputs) {
    const current = await readIconInput(output.path, 'utf8').catch(() => null);
    if (current !== output.content)
      fail('COLORFUL_ENTRY_DRIFT', path.relative(PACKAGE_ROOT, output.path));
  }
  return `COLORFUL_ENTRIES_OK ${publicRows(inventory).length}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.stdout.write(await runColorfulEntryGenerator());
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
